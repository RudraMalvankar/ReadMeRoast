"use client";

import React, { useState } from "react";
import { Flame, Copy, Check, Share2, Quote } from "lucide-react";

interface RoastCardProps {
  roast: string;
  repoFullName: string;
  score: number;
}

export function RoastCard({ roast, repoFullName, score }: RoastCardProps) {
  const [copiedRoast, setCopiedRoast] = useState(false);
  const [copiedShare, setCopiedShare] = useState(false);

  const handleCopyRoast = () => {
    navigator.clipboard.writeText(roast);
    setCopiedRoast(true);
    setTimeout(() => setCopiedRoast(false), 2000);
  };

  const handleShareRoast = () => {
    const text = `🔥 ReadMeRoast for ${repoFullName}: "${roast}"\nScore: ${score}/100\nCheck your repo at ReadMeRoast!`;
    navigator.clipboard.writeText(text);
    setCopiedShare(true);
    setTimeout(() => setCopiedShare(false), 2000);
  };

  return (
    <div className="relative rounded-xl border border-orange-500/30 bg-gradient-to-b from-[#181215] to-[#121118] p-6 shadow-2xl">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-orange-500/20 pb-4 mb-5">
        <div className="flex items-center gap-2 text-xs font-mono font-bold uppercase tracking-wider text-orange-400">
          <div className="flex h-6 w-6 items-center justify-center rounded bg-orange-500/20 border border-orange-500/30">
            <Flame className="h-4 w-4 fill-orange-400 text-orange-400" />
          </div>
          <span>The Roast</span>
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleCopyRoast}
            className="flex items-center gap-1.5 rounded-md border border-white/[0.08] bg-zinc-900/90 px-3 py-1.5 text-xs font-mono text-zinc-300 hover:border-zinc-700 hover:text-white transition-colors"
          >
            {copiedRoast ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-400" />
                <span className="text-emerald-400">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="h-3.5 w-3.5" />
                <span>Copy Roast</span>
              </>
            )}
          </button>

          <button
            type="button"
            onClick={handleShareRoast}
            className="flex items-center gap-1.5 rounded-md border border-orange-500/30 bg-orange-500/10 px-3 py-1.5 text-xs font-mono text-orange-300 hover:bg-orange-500/20 transition-colors"
          >
            {copiedShare ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-400" />
                <span className="text-emerald-400">Copied Share Text!</span>
              </>
            ) : (
              <>
                <Share2 className="h-3.5 w-3.5" />
                <span>Share</span>
              </>
            )}
          </button>
        </div>
      </div>

      <div className="relative pl-6 sm:pl-8">
        <div className="absolute left-0 top-0 text-orange-500/40">
          <Quote className="h-6 w-6 sm:h-7 sm:w-7 rotate-180" />
        </div>
        <p className="text-base sm:text-lg text-zinc-100 font-mono italic leading-relaxed">
          &ldquo;{roast}&rdquo;
        </p>
      </div>

      <div className="mt-5 pt-3 border-t border-white/[0.06] flex items-center justify-between text-[11px] text-zinc-400 font-mono">
        <span>Constructive developer critique • Generated by Gemma 2</span>
        <span>Target: Documentation clarity</span>
      </div>
    </div>
  );
}
